"""End-to-end reference pipeline and export of C headers for the firmware.

Pipeline (Figure 1 of the case study):
  mesh -> C, G (once) -> estimate (kappa, tau) -> posterior field x_hat
       -> lift to device sites with P (three weights per row) -> int8 model header.

Units: mesh coordinates in kilometres, field values and observations in millimetres.
All data are simulated with fixed seeds; nothing here is recorded data.
"""
from __future__ import annotations

import argparse
import struct
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import scipy.sparse as sp

from . import hmm, quant
from .estimate import Estimator, sample_field
from .fem import assemble
from .mesh import rect_mesh
from .projector import projector
from .spde import SpdePrecision


@dataclass
class PipelineResult:
    kappa_true: float
    tau_true: float
    kappa_hat: float
    tau_hat: float
    loglik_hat: float
    site_offset: np.ndarray
    P_dev: sp.csr_matrix
    params: hmm.HmmParams
    estimator: Estimator
    Y_train: np.ndarray


def true_theta(range_km: float = 0.6, sd_mm: float = 40.0):
    kappa = np.sqrt(8.0) / range_km
    tau = 1.0 / np.sqrt(4.0 * np.pi * kappa ** 2 * sd_mm ** 2)
    return float(kappa), float(tau)


def route_sites(n_sites: int = 64, lx: float = 1.5) -> np.ndarray:
    t = np.linspace(0.05, 0.95, n_sites)
    return np.column_stack([t * lx, (0.5 + 0.35 * np.sin(2.0 * np.pi * t)) * lx])


def run_pipeline(seed: int = 2026, nodes: int = 16, lx: float = 1.5, m: int = 200, R: int = 8,
                 sigma: float = 15.0, n_sites: int = 64) -> PipelineResult:
    rng = np.random.default_rng(seed)
    mesh = rect_mesh(nodes, nodes, lx, lx)
    Cd, G = assemble(mesh)
    spde = SpdePrecision(Cd, G)
    kappa, tau = true_theta()
    X = sample_field(spde, kappa, tau, rng, size=R)
    sensors = rng.uniform(0.0, lx, size=(m, 2))
    P = projector(mesh, sensors)
    Y = P @ X + sigma * rng.standard_normal((m, R))
    est = Estimator(spde, P, sigma)
    k_hat, t_hat, ll = est.fit(Y, kappa0=2.0, tau0=0.005)
    x_hat = est.posterior_mean(k_hat, t_hat, Y[:, -1])
    P_dev = projector(mesh, route_sites(n_sites, lx))
    offsets = P_dev @ x_hat
    params = hmm.HmmParams.default(offsets)
    return PipelineResult(kappa, tau, k_hat, t_hat, ll, offsets, P_dev, params, est, Y)


def _c_array(ctype: str, name: str, values, per_line: int = 12) -> str:
    vals = [str(int(v)) for v in np.asarray(values).ravel()]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def model_header(qm: quant.Int8Model, res: PipelineResult | None = None) -> str:
    out = ["/* Generated by python -m spdegmrf.export. Do not edit by hand. */",
           "#ifndef HMM_MODEL_GENERATED_H", "#define HMM_MODEL_GENERATED_H", "",
           '#include "hmm_filter.h"', ""]
    if res is not None:
        out.append(f"/* kappa_hat = {res.kappa_hat:.6g} (true {res.kappa_true:.6g}), "
                   f"tau_hat = {res.tau_hat:.6g} (true {res.tau_true:.6g}); simulated data. */")
    out.append(f"#define HMM_GEN_N_SITES {len(qm.site_offset_mm)}")
    out.append(_c_array("int16_t", "hmm_gen_site_offset_mm", qm.site_offset_mm))
    W = ",\n        ".join("{" + ", ".join(str(int(v)) for v in row) + "}" for row in qm.W)
    mu = ", ".join("{" + ", ".join(str(int(v)) for v in row) + "}" for row in qm.mu)
    isg = ", ".join("{" + ", ".join(str(int(v)) for v in row) + "}" for row in qm.inv_sigma_q16)
    out.append(f"""static const hmm_model_t hmm_gen_model = {{
    /* w (A transposed, int8, scale {qm.s_w:.8g}) */
    {{
        {W}
    }},
    /* bias */ {{0, 0, 0, 0}},
    /* fc_multiplier */ {qm.mult}, /* fc_shift */ {qm.shift},
    /* input_offset */ {qm.input_offset}, /* output_offset */ {qm.output_offset},
    /* mu (mm) */ {{{mu}}},
    /* inv_sigma_q16 */ {{{isg}}},
    /* lognorm_q16 */ {{{", ".join(str(int(v)) for v in qm.lognorm_q16)}}},
    /* offset_channel_mask */ {qm.offset_mask}u,
    /* site_offset_mm */ hmm_gen_site_offset_mm, /* n_sites */ HMM_GEN_N_SITES,
    /* init_belief */ {{{", ".join(str(int(v)) for v in qm.init_belief)}}}
}};
""")
    out.append("#endif /* HMM_MODEL_GENERATED_H */\n")
    return "\n".join(out)


def vectors_header(T: int, Yq, sites, q_beliefs, q_modes, f_modes, truth) -> str:
    out = ["/* Generated by python -m spdegmrf.export. Do not edit by hand. */",
           "#ifndef HMM_VECTORS_GENERATED_H", "#define HMM_VECTORS_GENERATED_H", "",
           "#include <stdint.h>", "", f"#define HMM_VEC_T {T}",
           _c_array("int16_t", "hmm_vec_obs_mm", Yq),
           _c_array("uint16_t", "hmm_vec_site", sites),
           _c_array("int8_t", "hmm_vec_expected_belief", q_beliefs),
           _c_array("uint8_t", "hmm_vec_expected_mode", q_modes),
           _c_array("uint8_t", "hmm_vec_float_mode", f_modes),
           _c_array("uint8_t", "hmm_vec_true_regime", truth),
           "#endif /* HMM_VECTORS_GENERATED_H */\n"]
    return "\n".join(out)


def write_gpu_case(path: Path, res: PipelineResult) -> None:
    """Binary case file read by gpu/src/main.cpp. Little-endian; layout documented in gpu/README.md."""
    est = res.estimator
    sp_ = est.spde
    P = est.P
    Y = np.asfortranarray(res.Y_train)
    with open(path, "wb") as f:
        f.write(b"SPDECASE")
        f.write(struct.pack("<iiiiid", sp_.n, sp_.nnz, P.shape[0], int(P.nnz), Y.shape[1], est.sigma))
        for arr, dt in ((sp_.indptr, "<i4"), (sp_.indices, "<i4"), (sp_.c_vals, "<f8"), (sp_.g_vals, "<f8"),
                        (sp_.k_vals, "<f8"), (P.indptr, "<i4"), (P.indices, "<i4"), (P.data, "<f8"),
                        (Y.ravel(order="F"), "<f8")):
            f.write(np.asarray(arr).astype(dt).tobytes())


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    ap.add_argument("--gpu-case", type=Path, default=None)
    ap.add_argument("--T", type=int, default=600)
    a = ap.parse_args(argv)
    res = run_pipeline()
    qm = quant.quantise(res.params)
    rng = np.random.default_rng(17)
    truth, sites, Y = hmm.simulate(res.params, a.T, rng)
    fb = hmm.forward_filter(res.params, Y, sites)
    Yq = quant.quantise_obs(Y)
    qb, qmodes = quant.Int8Filter(qm).run(Yq, sites)
    (a.root / "firmware/include/hmm_model_generated.h").write_text(model_header(qm, res))
    (a.root / "firmware/tests/hmm_vectors_generated.h").write_text(
        vectors_header(a.T, Yq, sites, qb, qmodes, fb.argmax(1), truth))
    if a.gpu_case:
        write_gpu_case(a.gpu_case, res)
    ag = quant.agreement(fb, qb, truth)
    print(f"kappa_hat={res.kappa_hat:.4f} (true {res.kappa_true:.4f}) tau_hat={res.tau_hat:.6f} "
          f"(true {res.tau_true:.6f})")
    print(f"int8 vs float: {ag}")


if __name__ == "__main__":
    main()
